tempat = ["Seattle", "New York", "Edinburgh", "Oslo", "Hawaii"]

print(tempat)

print(sorted(tempat))
print(tempat)

print(sorted(tempat, reverse=True))
print(tempat)

tempat.reverse()
print(tempat)

tempat.reverse()
print(tempat)

tempat.sort()
print(tempat)

tempat.sort(reverse=True)
print(tempat)