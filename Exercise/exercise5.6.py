age = 25

if age < 2:
    print("Orang itu adalah seorang bayi.")
elif age < 4:
    print("Orang itu adalah seorang balita.")
elif age < 13:
    print("Orang itu adalah seorang anak.")
elif age < 20:
    print("Orang itu adalah seorang remaja.")
elif age < 65:
    print("Orang itu adalah seorang dewasa.")
else:
    print("Orang itu adalah seorang lansia.")