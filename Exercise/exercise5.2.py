
city = 'solo'
print(city == 'solo')        
print(city == 'jakarta')     
print(city != 'jakarta')     
print(city != 'solo')        

# Metode lower()
language = 'Python'
print(language.lower() == 'python')   
print(language.lower() == 'Python')   

# Tes numerik
number = 10
print(number == 10)          
print(number == 5)           
print(number != 5)           
print(number != 10)          
print(number > 5)            
print(number > 10)           
print(number < 20)           
print(number < 10)           
print(number >= 10)          
print(number >= 11)          
print(number <= 10)          
print(number <= 9)           

# Kata kunci and dan or
print(number > 5 and number < 20)    
print(number > 5 and number < 8)     
print(number < 5 or number > 8)      
print(number < 5 or number > 20)     

