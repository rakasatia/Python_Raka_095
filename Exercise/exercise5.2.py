
kota = 'solo'
print(kota == 'solo')        
print(kota == 'jakarta')     
print(kota != 'jakarta')     
print(kota != 'solo')        

# Metode lower()
bahasa = 'Python'
print(bahasa.lower() == 'python')   
print(bahasa.lower() == 'Python')   

# Tes numerik
angka = 10
print(angka == 10)          
print(angka == 5)           
print(angka != 5)           
print(angka != 10)          
print(angka > 5)            
print(angka > 10)           
print(angka < 20)           
print(angka < 10)           
print(angka >= 10)          
print(angka >= 11)          
print(angka <= 10)          
print(angka <= 9)           

# Kata kunci and dan or
print(angka > 5 and angka < 20)    
print(angka > 5 and angka < 8)     
print(angka < 5 or angka > 8)      
print(angka < 5 or angka > 20)     

# Item ada di dalam list atau tidak
